// The start-up pictures of the app on an iPhone or an iPad's home screen (the white screen before the page opens on iOS: it does not read the
// colour of the manifest). iOS picks a picture by the exact size of the screen, so there is one for each device, in a light and a dark version
// (the dark one follows the appearance of the device). A picture is the colour of the theme with the logo in the middle.
//
//   node scripts/generate-ios-splash.mjs        writes public/splash/*.png and the <link> tags between the markers of index.html
//
// `splashEntries()` is what tests/ios-splash.test.js checks the files and index.html against.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

import { Resvg } from '@resvg/resvg-js';

const ROOT = new URL('../', import.meta.url);
export const THEMES = Object.freeze({ light: '#ffffff', dark: '#212121' });
const LOGO_CSS_WIDTH = 152; // the logo of the start-up screen of the page (9.5rem)

// [css width, css height, device pixel ratio] of the screen in portrait; the iPads also get landscape.
const IPHONES = [
  [440, 956, 3], [430, 932, 3], [402, 874, 3], [393, 852, 3], [428, 926, 3], [390, 844, 3], [375, 812, 3],
  [414, 896, 3], [414, 896, 2], [414, 736, 3], [375, 667, 2], [320, 568, 2]
];
const IPADS = [
  [1032, 1376, 2], [1024, 1366, 2], [834, 1210, 2], [834, 1194, 2], [820, 1180, 2], [834, 1112, 2], [810, 1080, 2], [768, 1024, 2], [744, 1133, 2]
];

export function splashEntries() {
  const entries = [];
  for (const [width, height, ratio] of IPHONES) entries.push({ width, height, ratio, orientation: 'portrait' });
  for (const [width, height, ratio] of IPADS) {
    entries.push({ width, height, ratio, orientation: 'portrait' });
    entries.push({ width: height, height: width, ratio, orientation: 'landscape' });
  }
  return entries.flatMap((entry) => Object.keys(THEMES).map((theme) => ({
    ...entry,
    theme,
    pixelWidth: entry.width * entry.ratio,
    pixelHeight: entry.height * entry.ratio,
    file: `splash/${theme}-${entry.width * entry.ratio}x${entry.height * entry.ratio}.png`,
  })));
}

export const linkTag = (entry) => `    <link rel="apple-touch-startup-image" href="/${entry.file}" media="(device-width: ${entry.width}px) and (device-height: ${entry.height}px) and (-webkit-device-pixel-ratio: ${entry.ratio}) and (orientation: ${entry.orientation})${entry.theme === 'dark' ? ' and (prefers-color-scheme: dark)' : ' and (prefers-color-scheme: light)'}" />`;

export const START_MARKER = '    <!-- ios-splash:start (generated by scripts/generate-ios-splash.mjs) -->';
export const END_MARKER = '    <!-- ios-splash:end -->';
export const linkBlock = () => [START_MARKER, ...splashEntries().map(linkTag), END_MARKER].join('\n');

function render(entry, logoBase64) {
  const logo = Math.round(LOGO_CSS_WIDTH * entry.ratio);
  const x = Math.round((entry.pixelWidth - logo) / 2);
  const y = Math.round(entry.pixelHeight * 0.44 - logo / 2);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${entry.pixelWidth}" height="${entry.pixelHeight}" viewBox="0 0 ${entry.pixelWidth} ${entry.pixelHeight}"><rect width="100%" height="100%" fill="${THEMES[entry.theme]}"/><image x="${x}" y="${y}" width="${logo}" height="${logo}" href="data:image/png;base64,${logoBase64}"/></svg>`;
  return new Resvg(svg).render().asPng();
}

export async function generate() {
  const logo = (await readFile(new URL('public/logo.png', ROOT))).toString('base64');
  await mkdir(new URL('public/splash/', ROOT), { recursive: true });
  for (const entry of splashEntries()) await writeFile(new URL(`public/${entry.file}`, ROOT), render(entry, logo));
  const indexUrl = new URL('index.html', ROOT);
  const html = await readFile(indexUrl, 'utf8');
  const start = html.indexOf(START_MARKER);
  const end = html.indexOf(END_MARKER);
  if (start === -1 || end === -1) throw new Error('index.html has no ios-splash markers.');
  await writeFile(indexUrl, `${html.slice(0, start)}${linkBlock()}${html.slice(end + END_MARKER.length)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  await generate();
  console.log(`Wrote ${splashEntries().length} start-up pictures and their links.`);
}
