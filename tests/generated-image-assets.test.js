test('keeps temporary generated images in memory until permanent save', async () => {
  const values = new Map();
  let persist = false;
  const store = createGeneratedImageAssetStore({
    setItem: async (key, value) => values.set(key, value),
    getItem: async key => values.get(key),
    getUserName: () => 'alice',
    randomUUID: () => 'temporary-asset',
    shouldPersist: () => persist
  });

  const descriptor = await store.save({ b64Json: 'aGVsbG8=', mediaType: 'image/png' });

  assert.equal(descriptor.ephemeral, true);
  assert.equal('storageKey' in descriptor, false);
  assert.equal(values.size, 0);
  assert.equal(await (await store.getBlob(descriptor)).text(), 'hello');

  persist = true;
  await store.persist(descriptor);
  assert.equal(descriptor.ephemeral, undefined);
  assert.equal(descriptor.storageKey, 'generatedImage:alice:temporary-asset');
  assert.equal(await values.get(descriptor.storageKey).text(), 'hello');
});

test('binds an object URL and original download name to generated image elements', async () => {
  const blob = new Blob(['hello'], { type: 'image/png' });
  const attrs = new Map();
  const image = { src: '' };
  const link = { href: '', download: '' };
  const root = {
    querySelectorAll(selector) {
      if (selector === '[data-generated-image-id="asset-1"]') return [image];
      if (selector === '[data-generated-image-download="asset-1"]') return [link];
      return [];
    },
    setAttribute(name, value) { attrs.set(name, value); }
  };
  const store = createGeneratedImageAssetStore({
    setItem: async () => {},
    getItem: async () => blob,
    getUserName: () => 'alice',
    createObjectURL: () => 'blob:asset-1'
  });

  await store.bind(root, [{ id: 'asset-1', storageKey: 'key', mediaType: 'image/png' }]);

  assert.equal(image.src, 'blob:asset-1');
  assert.equal(link.href, 'blob:asset-1');
  assert.match(link.download, /^noureon-\d{8}-\d{4}-1\.png$/, 'noureon-<day>-<minute>-<number> when the picture has no words');
});

test('a drawing kept without a size is read at the size every picture has, and the file kept is not touched', async () => {
  const kept = new Map();
  const raw = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 60"><rect width="100" height="60"/></svg>';
  const store = createGeneratedImageAssetStore({ getItem: async (key) => kept.get(key), setItem: async (key, value) => kept.set(key, value), getUserName: () => 'u' });
  kept.set('k', new Blob([raw], { type: 'image/svg+xml' }));
  const text = await (await store.getBlob({ id: 'd', mediaType: 'image/svg+xml', storageKey: 'k' })).text();
  assert.match(text, /^<svg width="1024" height="614" xmlns=/);
  assert.equal(await kept.get('k').text(), raw, 'what is kept stays as it was');
  const png = new Blob(['x'], { type: 'image/png' });
  kept.set('p', png);
  assert.equal(await store.getBlob({ id: 'p', mediaType: 'image/png', storageKey: 'p' }), png, 'a picture is given as it is');
});

test('an SVG picture and its download link get a data: address, never a blob: one that a tab could open as a page of the app', async () => {
  const blob = new Blob(['<svg xmlns="http://www.w3.org/2000/svg"><script>1</script></svg>'], { type: 'image/svg+xml' });
  const image = { src: '' };
  const link = { href: '', download: '' };
  const root = {
    querySelectorAll(selector) {
      if (selector === '[data-generated-image-id="asset-1"]') return [image];
      if (selector === '[data-generated-image-download="asset-1"]') return [link];
      return [];
    },
    setAttribute() {}
  };
  let blobUrls = 0;
  const store = createGeneratedImageAssetStore({ setItem: async () => {}, getItem: async () => blob, getUserName: () => 'alice', createObjectURL: () => { blobUrls += 1; return 'blob:asset-1'; } });

  await store.bind(root, [{ id: 'asset-1', storageKey: 'key', mediaType: 'image/svg+xml' }]);

  assert.match(image.src, /^data:image\/svg\+xml;base64,/);
  assert.equal(link.href, image.src);
  assert.equal(blobUrls, 0, 'no blob: address was made for it');
  assert.match(Buffer.from(image.src.split(',')[1], 'base64').toString('utf8'), /^<svg [^>]*><script>1<\/script><\/svg>$/, 'the file itself, as it is kept');
});
